/**Составить программу вычисления таблицы значений 
функции f(x) из задачи 1.1 для n значений аргумента x, 
равномерно распределённых на отрезке [a, b]. Для проверки 
программы задать n = 10; a = 0,50; b = 1,00. Результаты 
выдать в виде таблицы, в каждой строке каждой порядковый 
номер, значение аргумента и значение функции с шестью знаками после 
запятой.
*/

#include <locale.h>
#include <stdio.h>
#include <math.h>


int main()
{
    setlocale(LC_ALL, "");

    double a, b, x , y, nn;
    int n;

    printf("\nВведите левую границу отрезка a: ");scanf("%lf", &a);scanf("%*[^\n]");
    printf("\nВведите правую границу отрезка b: ");scanf("%lf", &b);scanf("%*[^\n]");
    printf("\nВведите количество точек n: ");scanf("%d", &n); scanf("%*[^\n]");

    printf("\nВведено границу отрезка [a;b]: [%2.2f;%2.2f]\nВведено количество точек n: %2d\n\n", a,b,n);
    if (a < 0 || a >= 100 || b <= a || b >= 100 || n < 2 || n >= 100){
        printf("\nОшибка: некорректные входные данные. Проверьте, что a >= 0, b > a и n >= 2.\n\n");
    }else{

    nn = (b - a)/(n-1);

    printf("\tТАБЛИЦА ФУНКЦИИ\t\n");
    printf(" _____________________________\n");
    printf("| n  |     x     |    f(x)    |\n");
    printf(" ----+-----------+------------\n");

    for (int i = 0;i != n;i++) {
        x = a + nn*i;
        y = 1.0/3 * pow(exp(6.3+sqrt(x)),1.0/7)*fabs(cos(2.0*x/3)-x);
        printf("| %-2d | %9.6f | %10.6f |\n", i+1, x, y);}

    printf(" ==== =========== ============\n");

    }
    return 0;
}
